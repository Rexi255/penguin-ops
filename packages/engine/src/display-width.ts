/** Combining marks and format characters, which take no cell. */
const ZERO_WIDTH = /^[\p{Mn}\p{Me}\p{Cf}]$/u;

/** The soft hyphen is a format character, but glibc gives it one cell. */
const SOFT_HYPHEN = "­";

/** The medial vowels and final consonants of Hangul Jamo join the syllable before them. */
const HANGUL_JAMO_JOINING: readonly [number, number] = [0x1160, 0x11ff];

/**
 * Returns how many cells `text` takes on a terminal: the sum of the widths of its characters.
 * Control characters count as one cell; commands quote them before they lay out names.
 */
export function displayWidth(text: string): number {
  let width = 0;
  for (const character of text) {
    width += characterWidth(character);
  }
  return width;
}

function characterWidth(character: string): number {
  const codePoint = character.codePointAt(0) ?? 0;
  if (character !== SOFT_HYPHEN && ZERO_WIDTH.test(character)) {
    return 0;
  }
  if (inRange(codePoint, HANGUL_JAMO_JOINING)) {
    return 0;
  }
  return WIDE_RANGES.some((range) => inRange(codePoint, range)) ? 2 : 1;
}

function inRange(codePoint: number, [first, last]: readonly [number, number]): boolean {
  return codePoint >= first && codePoint <= last;
}
